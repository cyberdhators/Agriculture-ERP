// Writes apps/web/lib/places/national.ts from docs/data/locations.csv.
//
// The location hierarchy lives in the database (scripts/locations-reseed.mjs)
// and, for the screens that need it before anyone has signed in -- the
// sign-up form, the public marketplace filter -- as this generated module.
// Both read the same CSV. tests/places-national.test.ts fails if the module
// and the CSV disagree, so a CSV edit without a rerun of this script is
// caught by the suite, not by a farmer.
//
//   node scripts/places-module.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { loadSource, toTree } from './locations-lib.mjs';

const { placeholder, rows } = loadSource();
if (placeholder) {
  console.error('docs/data/locations.csv is missing: refusing to write the placeholder set.');
  process.exit(1);
}
const tree = toTree(rows);
const byName = (a, b) => a.name.localeCompare(b.name);

const out = `// GENERATED by scripts/places-module.mjs from docs/data/locations.csv.
// Do not edit by hand: edit the CSV, rerun the script, and the reseed.

export interface PlaceState {
  id: string;
  name: string;
}

export interface PlaceCounty {
  id: string;
  name: string;
  stateId: string;
}

export interface PlacePayam {
  id: string;
  name: string;
  countyId: string;
  stateId: string;
}

export const NATIONAL_STATES: readonly PlaceState[] = ${JSON.stringify(
  [...tree.states].sort(byName).map((s) => ({ id: s.id, name: s.name })),
  null,
  2,
)};

export const NATIONAL_COUNTIES: readonly PlaceCounty[] = ${JSON.stringify(
  [...tree.counties].sort(byName).map((c) => ({ id: c.id, name: c.name, stateId: c.state_id })),
  null,
  2,
)};

export const NATIONAL_PAYAMS: readonly PlacePayam[] = ${JSON.stringify(
  [...tree.payams]
    .sort(byName)
    .map((p) => ({ id: p.id, name: p.name, countyId: p.county_id, stateId: p.state_id })),
  null,
  2,
)};
`;

const target = join(dirname(fileURLToPath(import.meta.url)), '../apps/web/lib/places/national.ts');
writeFileSync(target, out);
console.log(
  `wrote ${target}: ${tree.states.length} states, ${tree.counties.length} counties, ${tree.payams.length} payams`,
);
