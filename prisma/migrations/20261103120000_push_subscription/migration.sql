-- 2026-11-03 -- PUSH ALERTS ON A PHONE. The owner's decision; docs/DECISIONS.md,
-- "Push alerts on a phone".
--
-- ADDITIVE: one new table. No existing table, column or row changes, except
-- the audit CHECK rebuilt with every key of
-- 20261103110000_audit_action_ratings_archive (200) plus
-- push_subscription.created and push_subscription.removed (202). Any later CHECK
-- migration starts from this list.
--
-- One row per phone. `endpoint` is unique across removed rows too: a phone
-- that turns alerts on again, or passes to another account, reuses its row.
-- Row-level security with no policies, as every table: only API routes reach it.

CREATE TABLE "public"."push_subscription" (
    "id"           UUID        NOT NULL DEFAULT gen_random_uuid(),
    "auth_user_id" UUID        NOT NULL,
    "endpoint"     TEXT        NOT NULL,
    "p256dh"       TEXT        NOT NULL,
    "auth"         TEXT        NOT NULL,
    "language"     TEXT        NOT NULL,
    "created_at"   TIMESTAMPTZ NOT NULL DEFAULT now(),
    "updated_at"   TIMESTAMPTZ NOT NULL DEFAULT now(),
    "deleted_at"   TIMESTAMPTZ,

    CONSTRAINT "push_subscription_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "push_subscription_language_known" CHECK ("language" IN ('en', 'ar')),
    CONSTRAINT "push_subscription_endpoint_length" CHECK (char_length("endpoint") <= 1000)
);

CREATE UNIQUE INDEX "push_subscription_endpoint_key"
    ON "public"."push_subscription" ("endpoint");
CREATE INDEX "push_subscription_account_idx"
    ON "public"."push_subscription" ("auth_user_id");

ALTER TABLE "public"."push_subscription" ENABLE ROW LEVEL SECURITY;

